# We build function in python using 'def' keyword.
def hello():
    print("this is the hello function so i am doing hello")

hello() #Here function is called.

# Parameters and arguments in function-
# Parameter is the thing you accept and argument is the thing you provide.
def sum(a,b): #Here 'a' and 'b' are parameters
    print(f"The sum of your number is {a+b}")

sum(12,14) #Output-26 ,here 12 and 14 are arguments.
sum(24,45) #Output-69
